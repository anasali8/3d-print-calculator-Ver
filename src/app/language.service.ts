@Injectable({providedIn: 'root'})
export class LanguageService {
  readonly lang = signal<Language>('ar');
  constructor() {
    let saved: string | null = null;
    try { saved = localStorage.getItem('layerprice-language'); } catch {}
    this.set(saved === 'en' ? 'en' : 'ar');
  }
  set(language: Language) {
    this.lang.set(language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.title = this.t('3D Print Calculator');
    try { localStorage.setItem('layerprice-language', language); } catch {}
  }
  t(text: string): string {
    return this.lang() === 'ar' && Object.hasOwn(arabic, text) ? arabic[text] : text;
  }
  color(text: string): string {
    const names = ['Black','White','Red','Blue','Green','Yellow','Orange','Pink','Purple','Gray','Grey','Silver','Gold','Brown','Transparent'];
    const match = names.find(name => name.toLowerCase() === text.trim().toLowerCase() || arabic[name] === text.trim());
    return match ? this.t(match) : text;
  }
}
